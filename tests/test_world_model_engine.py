"""Meterless World Model engine: conformance checks + cross-validation against the TypeScript reference.

tests/data/world_model_golden.json was generated by running the Meterless TypeScript reference
(engines/world-model/reference) on the same inputs; the Python engine must reproduce it exactly.
The eight conformance checks mirror conformance/runner.ts one for one.
"""

import json
from datetime import datetime, timezone
from pathlib import Path

import pytest

from engines.world_model import (WorldModel, canonical_json, context_id_from_attrs, decide, entity_id_from_name,
                                 external_id, fact_id, name_similarity, normalize_name, relationship_id, sha256_hex)

GOLDEN = json.loads((Path(__file__).parent / "data" / "world_model_golden.json").read_text(encoding="utf-8"))


def clock():
    return datetime(2026, 5, 18, tzinfo=timezone.utc)


OBSERVATIONS = [
    {"externalId": "a1", "title": "Fed holds rates", "at": "2026-05-17T14:00:00.000Z",
     "source": {"kind": "rss", "at": "2026-05-17T14:00:00.000Z"}, "entities": [{"type": "person", "name": "Jerome Powell"}]},
    {"externalId": "a2", "title": "Powell signals patience", "at": "2026-05-17T16:30:00.000Z",
     "source": {"kind": "rss", "at": "2026-05-17T16:30:00.000Z"}, "entities": [{"type": "person", "name": "Jerome Powell"}]},
]
GOLDEN_OBSERVATIONS = OBSERVATIONS + [
    {"externalId": "a3", "title": "Gold rallies", "at": "2026-05-17T18:00:00.000Z",
     "source": {"kind": "rss", "at": "2026-05-17T18:00:00.000Z"},
     "entities": [{"type": "commodity", "name": "Gold"}, {"type": "person", "name": "Jerome Powell"}]},
]


def at(s):
    return {"kind": "agent", "by": "t", "at": s}


# ----------------------------------------------------------- the 8 conformance checks (runner.ts)
def test_sid_001_diacritics_and_nbsp_normalize_identically():
    assert normalize_name("José  García") == normalize_name("Jose Garcia")
    assert entity_id_from_name("person", "José García") == entity_id_from_name("person", "jose garcia")


def test_sid_002_distinct_names_stay_distinct():
    assert entity_id_from_name("org", "Acme Corp") != entity_id_from_name("org", "Acme Corporation")
    assert entity_id_from_name("person", "x") != entity_id_from_name("org", "x")


def test_band_001_merge_bands_at_the_boundaries():
    assert decide(0.85) == "auto-merge"
    assert decide(0.84) == "review"
    assert decide(0.82) == "review"
    assert decide(0.81) == "new"


def test_prov_001_writes_without_provenance_are_rejected():
    world = WorldModel("conf")
    with pytest.raises(ValueError):
        world.upsert_entity(type="person", name="No Provenance", source=None)
    with pytest.raises(ValueError):
        world.upsert_entity(type="person", name="No Provenance", source={"kind": "agent"})  # no `at`
    assert world.state_shape()["entities"] == []


def test_idem_001_same_batch_twice_is_an_empty_diff():
    world = WorldModel("conf", clock=clock)
    world.ingest(OBSERVATIONS)
    shape1 = world.state_shape_canonical()
    second = world.ingest(OBSERVATIONS)
    assert second["changed"] is False
    assert world.state_shape_canonical() == shape1


def test_idem_002_the_idempotency_check_can_fail():
    world = WorldModel("conf", clock=clock)
    world.ingest(OBSERVATIONS)
    shape1 = world.state_shape_canonical()
    mutated = [{**OBSERVATIONS[0], "title": OBSERVATIONS[0]["title"] + " (edited)"}, OBSERVATIONS[1]]
    run = world.ingest(mutated)
    assert run["changed"] is True
    assert world.state_shape_canonical() != shape1


def test_bitemp_001_superseding_edge_closes_the_old_one():
    world = WorldModel("conf")

    def manual(s):
        return {"kind": "manual", "at": s}
    world.upsert_entity("player", external_key={"system": "g", "id": "p1"}, source=manual("2087-01-01T00:00:00.000Z"))
    world.upsert_entity("team", external_key={"system": "g", "id": "a"}, source=manual("2087-01-01T00:00:00.000Z"))
    world.upsert_entity("team", external_key={"system": "g", "id": "b"}, source=manual("2088-03-01T00:00:00.000Z"))
    world.relate("player:g:p1", "plays-for", "team:g:a", valid_from="2087-01-01T00:00:00.000Z", source=manual("2087-01-01T00:00:00.000Z"))
    world.relate("player:g:p1", "plays-for", "team:g:b", valid_from="2088-03-01T00:00:00.000Z", source=manual("2088-03-01T00:00:00.000Z"))
    now = world.view("graph").neighbors_of("player:g:p1", via="plays-for")
    assert [e["id"] for e in now] == ["team:g:b"]
    then = world.view("graph").neighbors_of("player:g:p1", via="plays-for", at="2087-06-01T00:00:00.000Z")
    assert [e["id"] for e in then] == ["team:g:a"]


def test_audit_001_every_mutation_writes_an_audit_entry_in_order():
    world = WorldModel("conf")
    world.upsert_entity("x", name="Audit One", source={"kind": "manual", "at": "2026-01-01T00:00:00.000Z"})
    world.upsert_entity("x", name="Audit Two", source={"kind": "manual", "at": "2026-01-02T00:00:00.000Z"})
    audit = world.audit()
    assert len(audit) >= 2
    assert all(audit[i]["seq"] > audit[i - 1]["seq"] for i in range(1, len(audit)))


# ----------------------------------------------------------- cross-validation against the TS reference
def test_normalize_and_entity_ids_match_the_typescript_reference():
    for raw, expected in GOLDEN["normalize"]:
        assert normalize_name(raw) == expected
    for type_, raw, expected in GOLDEN["entityIds"]:
        assert entity_id_from_name(type_, raw) == expected


def test_hashes_and_content_addressed_ids_match_the_reference():
    for text, expected in GOLDEN["sha"]:
        assert sha256_hex(text) == expected
    assert canonical_json({"b": 1, "a": [2, {"z": 1, "y": None}], "c": 1.0, "d": "é"}) == GOLDEN["canonical"][0]
    assert external_id("claim", "vidhur", "r1-C1") == GOLDEN["externalId"]
    rel_a, rel_b = GOLDEN["relId"].split("|")
    assert relationship_id("a", "mentions", "b") == rel_a
    assert relationship_id("a", "t", "b", "ctx", "2026-01-01T00:00:00.000Z") == rel_b
    assert fact_id("e1", "p", {"v": 1.5, "w": [1, 2]}, "2026-01-01T00:00:00.000Z", "agent") == GOLDEN["factId"]
    assert context_id_from_attrs("week", {"n": 14}, "season:g:145") == GOLDEN["ctxId"]


def test_similarity_and_banding_match_the_reference():
    for a, b, similarity, decision in GOLDEN["sims"]:
        assert name_similarity(a, b) == pytest.approx(similarity)
        assert decide(name_similarity(a, b)) == decision


def test_ingest_world_state_is_byte_identical_to_the_reference():
    world = WorldModel("g", clock=clock)
    world.ingest(GOLDEN_OBSERVATIONS)
    assert world.state_shape_canonical() == GOLDEN["ingestShapeCanonical"]
    assert world.ingest(GOLDEN_OBSERVATIONS)["changed"] is GOLDEN["secondChanged"]


def test_entity_fact_relationship_writes_match_the_reference():
    world = WorldModel("g2")
    world.upsert_entity("claim", external_key={"system": "vidhur", "id": "C1"}, attrs={"pct": 3.5, "dir": "cost_up"}, source=at("2026-01-01T00:00:00.000Z"))
    world.upsert_entity("claim", external_key={"system": "vidhur", "id": "C1"}, attrs={"status": "PASS"}, source=at("2026-01-02T00:00:00.000Z"))
    world.assert_fact("claim:vidhur:C1", "impact", {"worst": 10.5}, confidence=0.9, source=at("2026-01-03T00:00:00.000Z"))
    world.relate("claim:vidhur:C1", "audited-by", "verdict:vidhur:V1", valid_from="2026-01-02T00:00:00.000Z", source=at("2026-01-02T00:00:00.000Z"))
    assert world.state_shape_canonical() == GOLDEN["w2Shape"]
    assert [[a["seq"], a["kind"], a["actor"], a["summary"]] for a in world.audit()] == GOLDEN["w2Audit"]


# ----------------------------------------------------------- event sourcing
def test_state_is_rebuilt_by_replaying_the_event_log(tmp_path):
    path = tmp_path / "w.json"
    world = WorldModel("persist", path=str(path))
    world.upsert_entity("claim", external_key={"system": "v", "id": "1"}, attrs={"a": 1}, source={"kind": "agent", "at": "2026-01-01T00:00:00.000Z"})
    world.upsert_entity("claim", external_key={"system": "v", "id": "1"}, attrs={"b": 2}, source={"kind": "agent", "at": "2026-01-02T00:00:00.000Z"})
    reloaded = WorldModel("persist", path=str(path))
    assert reloaded.view("graph").entity("claim:v:1")["attrs"] == {"a": 1, "b": 2}
    assert reloaded.state_shape_canonical() == world.state_shape_canonical()
    # the log is append-only and time-travel works: before the second write only `a` existed
    assert reloaded.view("snapshot").entity_at("claim:v:1", "2026-01-01T12:00:00.000Z")["attrs"] == {"a": 1}


def test_near_duplicate_names_auto_merge():
    world = WorldModel("res")
    src = {"kind": "manual", "at": "2026-01-01T00:00:00.000Z"}
    first = world.upsert_entity("person", name="Jerome Powell", source=src)
    merged = world.upsert_entity("person", name="Jerome Powel", source=src)  # similarity 0.92 -> auto-merge
    assert merged["id"] == first["id"]
    assert len(world.view("graph").query(type="person")) == 1
